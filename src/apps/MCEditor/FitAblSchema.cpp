VARTYPE FitAblColumnVarType(const char* table, const char* column)
{
    for (const FitAblColumnType& entry : FITABL_COLUMN_TYPES)
    {
        if (_stricmp(entry.table, table) == 0 && _stricmp(entry.column, column) == 0)
        {
            return entry.type;
        }
    }

    return VT_EMPTY;
}
