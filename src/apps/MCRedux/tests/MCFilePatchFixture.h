    /// <summary>
    /// <paramref name="count"/> bytes, each the top byte of its index (from <paramref name="start"/>) times
    /// <paramref name="multiplier"/>.
    /// </summary>
    inline std::vector<uint8_t> Hashed(size_t count, uint32_t multiplier, uint32_t start)
    {
        std::vector<uint8_t> bytes(count);

        for (size_t i = 0; i < count; ++i)
        {
            bytes[i] = static_cast<uint8_t>(((static_cast<uint32_t>(i) + start) * multiplier) >> HashedByteShift);
        }

        return bytes;
    }

    inline std::vector<uint8_t> PatchOld()
    {
        return Hashed(PatchOldSize, PatchOldMultiplier, 0);
    }

    inline std::vector<uint8_t> PatchNew()
    {
        const std::vector<uint8_t> old = PatchOld();
        const std::vector<uint8_t> fresh = Hashed(PatchFreshSize, PatchFreshMultiplier, PatchFreshStart);
        std::vector<uint8_t> made(old.begin(), old.begin() + PatchKeptHead);
        made.insert(made.end(), fresh.begin(), fresh.end());
        made.insert(made.end(), old.begin() + PatchCutEnd, old.end());
        made.insert(made.end(), old.begin(), old.begin() + PatchRepeatedHead);
        return made;
    }
